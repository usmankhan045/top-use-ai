import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const inputPath = process.argv[2] ?? "/tmp/aifoxx-tools.json";
const outputPath =
  process.argv[3] ?? "supabase/migrations/005_import_complete_tool_catalog.sql";
const sourceUrl = "https://github.com/withkarann/aifoxx";
const sourceLicense = "MIT";
const importedAt = "2026-10-20T00:00:00.000Z";
const siteId = "7635559c-2c64-4d76-8b3b-1c69e4a412f8";

const raw = await readFile(inputPath, "utf8");
const tools = JSON.parse(raw);

if (!Array.isArray(tools) || tools.length < 900) {
  throw new Error(`Refusing to generate an incomplete catalog (${tools.length} rows).`);
}

const required = ["id", "name", "slug", "category", "description", "url", "pricing"];
const seenIds = new Set();
const seenSlugs = new Set();

for (const [index, tool] of tools.entries()) {
  for (const field of required) {
    if (typeof tool[field] !== "string" || !tool[field].trim()) {
      throw new Error(`Record ${index} has an invalid ${field}.`);
    }
  }
  if (seenIds.has(tool.id)) throw new Error(`Duplicate source id: ${tool.id}`);
  if (seenSlugs.has(tool.slug)) throw new Error(`Duplicate slug: ${tool.slug}`);
  seenIds.add(tool.id);
  seenSlugs.add(tool.slug);
}

const snapshotHash = createHash("sha256").update(raw).digest("hex");
const json = JSON.stringify(tools).replaceAll("$catalog$", "$catalog_split$");

const sql = `-- Generated by scripts/catalog/generate-aifoxx-migration.mjs.
-- Complete ${tools.length}-record AIFOXX snapshot. The application reads its own
-- Supabase tables at runtime; this upstream source is not queried by users.

alter table tool_catalog
  add column if not exists source_record_id text,
  add column if not exists source_category text,
  add column if not exists subcategory text,
  add column if not exists website_url text,
  add column if not exists pricing_model text,
  add column if not exists pricing_details jsonb not null default '{}'::jsonb,
  add column if not exists tags text[] not null default '{}',
  add column if not exists use_cases text[] not null default '{}',
  add column if not exists not_good_for text[] not null default '{}',
  add column if not exists industries text[] not null default '{}',
  add column if not exists access_methods text[] not null default '{}',
  add column if not exists compliance jsonb not null default '{}'::jsonb,
  add column if not exists compliance_sources jsonb not null default '{}'::jsonb,
  add column if not exists data_storage jsonb not null default '{}'::jsonb,
  add column if not exists featured boolean not null default false,
  add column if not exists popular boolean not null default false,
  add column if not exists source_status text,
  add column if not exists source_dataset text,
  add column if not exists source_imported_at timestamptz,
  add column if not exists search_document tsvector;

alter table tool_catalog drop constraint if exists tool_catalog_pricing_model_check;
alter table tool_catalog add constraint tool_catalog_pricing_model_check
  check (pricing_model is null or pricing_model in ('free', 'freemium', 'free-trial', 'paid', 'pay-as-you-go', 'contact-sales', 'open-source', 'unknown'));

create table if not exists tool_catalog_imports (
  id uuid primary key default gen_random_uuid(),
  site_id uuid references sites(id) not null,
  source_name text not null,
  source_url text not null,
  source_license text,
  snapshot_sha256 text not null,
  record_count integer not null check (record_count > 0),
  imported_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique(site_id, source_name, snapshot_sha256)
);

create unique index if not exists idx_tool_catalog_source_record
  on tool_catalog(site_id, source_dataset, source_record_id)
  where source_dataset is not null and source_record_id is not null;
create index if not exists idx_tool_catalog_filters
  on tool_catalog(site_id, status, category, pricing_model);
create index if not exists idx_tool_catalog_source_category
  on tool_catalog(site_id, source_category, subcategory);
create index if not exists idx_tool_catalog_tags_gin on tool_catalog using gin(tags);
create index if not exists idx_tool_catalog_use_cases_gin on tool_catalog using gin(use_cases);
create index if not exists idx_tool_catalog_access_methods_gin on tool_catalog using gin(access_methods);
create index if not exists idx_tool_catalog_search_gin on tool_catalog using gin(search_document);

create or replace function refresh_tool_catalog_search_document()
returns trigger language plpgsql as $$
begin
  new.search_document := setweight(to_tsvector('english', coalesce(new.name, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(new.source_category, '') || ' ' || coalesce(new.subcategory, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(new.summary, '') || ' ' || coalesce(new.best_for, '')), 'B') ||
    setweight(to_tsvector('english', array_to_string(coalesce(new.tags, '{}'), ' ') || ' ' || array_to_string(coalesce(new.use_cases, '{}'), ' ')), 'C');
  return new;
end;
$$;

drop trigger if exists trg_tool_catalog_search_document on tool_catalog;
create trigger trg_tool_catalog_search_document
before insert or update of name, source_category, subcategory, summary, best_for, tags, use_cases
on tool_catalog for each row execute function refresh_tool_catalog_search_document();

with source_rows as (
  select * from jsonb_to_recordset($catalog$${json}$catalog$::jsonb) as x(
    id text, name text, slug text, category text, subcategory text,
    description text, url text, tags jsonb, pricing text, featured boolean,
    popular boolean, status text, last_verified text, access_methods jsonb,
    compliance jsonb, data_storage jsonb, pricing_detail jsonb, use_cases jsonb,
    not_good_for jsonb, industries jsonb, compliance_sources jsonb
  )
), normalized as (
  select
    x.*,
    case lower(x.pricing)
      when 'free' then 'free'
      when 'freemium' then 'freemium'
      when 'open source' then 'open-source'
      when 'paid' then case
        when coalesce(x.pricing_detail->>'free_tier', '') ~* 'trial' then 'free-trial'
        else 'paid' end
      when 'pay-as-you-go' then 'pay-as-you-go'
      when 'contact sales' then 'contact-sales'
      else 'unknown'
    end as normalized_pricing,
    coalesce((select array_agg(value) from jsonb_array_elements_text(coalesce(x.tags, '[]'))), '{}') as tags_array,
    coalesce((select array_agg(value) from jsonb_array_elements_text(coalesce(x.use_cases, '[]'))), '{}') as use_cases_array,
    coalesce((select array_agg(value) from jsonb_array_elements_text(coalesce(x.not_good_for, '[]'))), '{}') as not_good_for_array,
    coalesce((select array_agg(value) from jsonb_array_elements_text(coalesce(x.industries, '[]'))), '{}') as industries_array,
    coalesce((select array_agg(value) from jsonb_array_elements_text(coalesce(x.access_methods, '[]'))), '{}') as access_methods_array
  from source_rows x
)
insert into tool_catalog (
  site_id, slug, name, category, summary, best_for, audience, strengths, limitations,
  free_plan, paid_plans, quality_score, ease_score, value_score, related_post_slugs,
  status, verification_status, last_reviewed_at, source_record_id, source_category,
  subcategory, website_url, pricing_model, pricing_details, tags, use_cases,
  not_good_for, industries, access_methods, compliance, compliance_sources,
  data_storage, featured, popular, source_status, source_dataset, source_imported_at
)
select
  '${siteId}', n.slug, n.name,
  lower(regexp_replace(n.category, '[^a-zA-Z0-9]+', '-', 'g')),
  n.description,
  coalesce(nullif(n.use_cases->>0, ''), nullif(n.subcategory, ''), n.category),
  case when n.pricing in ('Free', 'Freemium', 'Open Source') then array['beginner']::text[] else '{}'::text[] end,
  n.use_cases_array,
  n.not_good_for_array,
  case when n.pricing in ('Free', 'Freemium', 'Open Source') then 'yes' else 'no' end,
  n.pricing in ('Freemium', 'Paid', 'Pay-as-you-go', 'Contact Sales'),
  3, 3,
  case when n.pricing in ('Free', 'Open Source') then 5 when n.pricing = 'Freemium' then 4 else 3 end,
  '{}'::text[],
  case when lower(coalesce(n.status, '')) = 'active' then 'published' else 'draft' end,
  'needs-review', nullif(n.last_verified, '')::timestamptz,
  n.id, n.category, n.subcategory, n.url, n.normalized_pricing,
  coalesce(n.pricing_detail, '{}'::jsonb), n.tags_array, n.use_cases_array,
  n.not_good_for_array, n.industries_array, n.access_methods_array,
  coalesce(n.compliance, '{}'::jsonb), coalesce(n.compliance_sources, '{}'::jsonb),
  coalesce(n.data_storage, '{}'::jsonb), coalesce(n.featured, false),
  coalesce(n.popular, false), n.status, 'aifoxx', '${importedAt}'::timestamptz
from normalized n
on conflict (site_id, slug) do update set
  name=excluded.name, category=excluded.category, summary=excluded.summary,
  best_for=excluded.best_for, strengths=excluded.strengths,
  limitations=excluded.limitations, free_plan=excluded.free_plan,
  paid_plans=excluded.paid_plans, value_score=excluded.value_score,
  status=excluded.status, last_reviewed_at=excluded.last_reviewed_at,
  source_record_id=excluded.source_record_id, source_category=excluded.source_category,
  subcategory=excluded.subcategory, website_url=excluded.website_url,
  pricing_model=excluded.pricing_model, pricing_details=excluded.pricing_details,
  tags=excluded.tags, use_cases=excluded.use_cases,
  not_good_for=excluded.not_good_for, industries=excluded.industries,
  access_methods=excluded.access_methods, compliance=excluded.compliance,
  compliance_sources=excluded.compliance_sources, data_storage=excluded.data_storage,
  featured=excluded.featured, popular=excluded.popular,
  source_status=excluded.source_status, source_dataset=excluded.source_dataset,
  source_imported_at=excluded.source_imported_at, updated_at=now();

insert into tool_catalog_imports
  (site_id, source_name, source_url, source_license, snapshot_sha256, record_count, imported_at, metadata)
values
  ('${siteId}', 'aifoxx', '${sourceUrl}', '${sourceLicense}', '${snapshotHash}', ${tools.length}, '${importedAt}',
   jsonb_build_object('generator', 'scripts/catalog/generate-aifoxx-migration.mjs'))
on conflict (site_id, source_name, snapshot_sha256) do nothing;

update tool_catalog set name=name
where site_id='${siteId}' and search_document is null;

insert into tool_sources (site_id, tool_id, source_type, url, label, retrieved_at, reliability)
select '${siteId}', t.id, 'dataset', '${sourceUrl}', 'AIFOXX catalog (MIT)', '${importedAt}', 0.75
from tool_catalog t
where t.site_id='${siteId}' and t.source_dataset='aifoxx'
  and not exists (
    select 1 from tool_sources s
    where s.tool_id=t.id and s.source_type='dataset' and s.url='${sourceUrl}'
  );

analyze tool_catalog;
`;

await writeFile(outputPath, sql);
console.log(`Wrote ${outputPath}: ${tools.length} tools, sha256 ${snapshotHash}`);
